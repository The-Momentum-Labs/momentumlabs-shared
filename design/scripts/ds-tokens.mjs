#!/usr/bin/env node
/**
 * ds-tokens.mjs — write the design system's token sheet for Claude Design from
 * the brand's real stylesheet, so the tokens Claude Design shows are the ones
 * the apps ship, not a hand-typed copy that drifts.
 *
 * Claude Design reads a design system's tokens from a plain css file named in
 * its manifest's globalCssPaths (styles.css at the root). It wants literal
 * values with a `@kind` annotation per declaration, and it treats a second
 * selector block as a theme:
 *
 *   :root{ --color-brand:#8b1a2b; /* @kind color *\/ ... }
 *   [data-theme="dark"]{ --color-brand:#a82540; /* @kind color *\/ ... }
 *
 * The brand sheet (momentumlabs-company/design-system/brand/index.css) keeps
 * its colours as rgb triplets (`--brand: 139 26 43`) so Tailwind can add alpha,
 * under `:root` for light and `.dark` for dark. Radii and shadows live in
 * brand/tailwind.config.ts. This tool reads both and emits the sheet.
 *
 * Only the semantic roles are carried, the "control surface" the brand sheet
 * itself names: the ~18 colour roles, the four font stacks, the tailwind radii
 * and shadows. Component-level vars (--editor-*, --input-*, --picker-*) are
 * not tokens and stay out.
 *
 * Usage:
 *   ds-tokens.mjs --css brand/index.css --tailwind brand/tailwind.config.ts
 *                 --out styles.css [--check]
 *   --check  write nothing; exit 1 when --out differs from what would be written
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The colour roles, in the order the sheet declares them. */
export const COLOR_ROLES = [
  'surface', 'surface-2', 'surface-3',
  'brand', 'brand-soft', 'cream', 'inverse',
  'ink', 'ink-soft', 'ink-brand', 'on-brand',
  'line', 'line-strong', 'line-brand',
  'success', 'danger', 'cardinal', 'cardinal-bright',
];
export const FONT_ROLES = ['font-base', 'font-serif-body', 'font-serif-display', 'font-mono'];

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');

/**
 * Every innermost `selector { declarations }` block, as [selector, Map].
 * Innermost is enough: the token blocks are flat. A duplicate name inside one
 * selector keeps the FIRST value, so a later override block cannot win.
 */
export function blocks(css) {
  const out = [];
  const re = /([^{}]*)\{([^{}]*)\}/g;
  let m;
  for (const src = stripComments(css); (m = re.exec(src)); ) {
    const selector = m[1].split(/[;}]/).pop().trim();
    const decls = new Map();
    for (const line of m[2].split(';')) {
      const d = /^\s*(--[A-Za-z0-9-]+)\s*:\s*(.+?)\s*$/.exec(line);
      if (d && !decls.has(d[1])) decls.set(d[1], d[2]);
    }
    out.push([selector, decls]);
  }
  return out;
}

/** Merges every block with the given selector, first value wins. */
export function declarations(css, selector) {
  const merged = new Map();
  for (const [sel, decls] of blocks(css)) {
    if (sel !== selector) continue;
    for (const [k, v] of decls) if (!merged.has(k)) merged.set(k, v);
  }
  return merged;
}

/** `139 26 43` -> `#8b1a2b`. Anything else is an error, not a guess. */
export function tripletToHex(value, name) {
  const m = /^(\d{1,3})\s+(\d{1,3})\s+(\d{1,3})$/.exec(value.trim());
  if (!m) throw new Error(`${name}: expected an rgb triplet, got "${value}"`);
  return '#' + m.slice(1).map((n) => Number(n).toString(16).padStart(2, '0')).join('');
}

/** `borderRadius: { lg: '0.75rem', ... }` -> [['lg','0.75rem'], ...] */
export function tailwindTable(ts, key) {
  const m = new RegExp(`${key}\\s*:\\s*\\{([^}]*)\\}`).exec(ts);
  if (!m) throw new Error(`tailwind config has no ${key} table`);
  return [...m[1].matchAll(/['"]?([A-Za-z0-9-]+)['"]?\s*:\s*'([^']*)'/g)].map((x) => [x[1], x[2]]);
}

export function buildTokens({ css, tailwind }) {
  const light = declarations(css, ':root');
  const dark = declarations(css, '.dark');
  const pick = (map, role, theme) => {
    const v = map.get(`--${role}`);
    if (v === undefined) throw new Error(`${theme}: --${role} is not declared`);
    return v;
  };
  const colors = (map, theme) => COLOR_ROLES.map((r) => [`--color-${r}`, tripletToHex(pick(map, r, theme), `--${r}`), 'color']);
  const fonts = FONT_ROLES.map((r) => [`--${r}`, pick(light, r, ':root'), 'font']);
  const radii = tailwindTable(tailwind, 'borderRadius').map(([k, v]) => [`--radius-${k}`, v, 'radius']);
  const shadows = tailwindTable(tailwind, 'boxShadow').map(([k, v]) => [`--shadow-${k}`, v, 'shadow']);
  return {
    light: [...colors(light, ':root'), ...fonts, ...radii, ...shadows],
    dark: colors(dark, '.dark'),
  };
}

export function renderSheet(tokens, source) {
  const line = ([name, value, kind]) => `${name}:${value}; /* @kind ${kind} */`;
  return [
    `/* GENERATED by the design skill (ds-tokens.mjs) from ${source}. Do not edit; edit the brand sheet and re-run: npm run design:tokens */`,
    ':root{',
    ...tokens.light.map(line),
    '}',
    '[data-theme="dark"]{',
    ...tokens.dark.map(line),
    '}',
    'a{color:var(--color-ink-brand)}a:hover{color:var(--color-cardinal-bright)}',
    '',
  ].join('\n');
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const argv = process.argv.slice(2);
  const arg = (flag) => {
    const i = argv.indexOf(flag);
    if (i === -1 || !argv[i + 1]) {
      console.error(`ds-tokens: ${flag} is required`);
      process.exit(1);
    }
    return resolve(process.cwd(), argv[i + 1]);
  };
  const cssPath = arg('--css');
  const twPath = arg('--tailwind');
  const outPath = arg('--out');
  try {
    const tokens = buildTokens({ css: readFileSync(cssPath, 'utf8'), tailwind: readFileSync(twPath, 'utf8') });
    const sheet = renderSheet(tokens, `${relative(process.cwd(), cssPath)} + ${relative(process.cwd(), twPath)}`);
    if (argv.includes('--check')) {
      let have = null;
      try { have = readFileSync(outPath, 'utf8'); } catch {}
      if (have !== sheet) {
        console.error(`ds-tokens: ${relative(process.cwd(), outPath)} is stale, re-run: npm run design:tokens`);
        process.exit(1);
      }
      console.log(`ds-tokens: ${relative(process.cwd(), outPath)} up to date (${tokens.light.length} light, ${tokens.dark.length} dark)`);
    } else {
      writeFileSync(outPath, sheet);
      console.log(`wrote ${relative(process.cwd(), outPath)} (${tokens.light.length} light, ${tokens.dark.length} dark)`);
    }
  } catch (e) {
    console.error(`ds-tokens: ${e.message}`);
    process.exit(1);
  }
}
