/**
 * Tests for the token sheet generator.
 * Run: node --test design/scripts/ds-tokens.test.mjs
 * The fixture mirrors brand/index.css: triplets under :root and .dark, fonts in
 * an earlier :root block, a later override block that must NOT win, and
 * comments around everything.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { blocks, declarations, tripletToHex, tailwindTable, buildTokens, renderSheet, COLOR_ROLES } from './ds-tokens.mjs';

const roles = (map) => Object.entries(map).map(([k, v]) => `  --${k}: ${v};`).join('\n');
const LIGHT = { surface: '250 247 244', 'surface-2': '242 238 233', 'surface-3': '232 227 221', brand: '139 26 43', 'brand-soft': '246 234 236', cream: '249 228 193', inverse: '26 23 20', ink: '26 23 20', 'ink-soft': '107 101 96', 'ink-brand': '139 26 43', 'on-brand': '250 247 244', line: '216 211 204', 'line-strong': '196 188 177', 'line-brand': '222 200 204', success: '74 142 79', danger: '220 38 38', cardinal: '139 26 43', 'cardinal-bright': '244 63 94' };
const DARK = { ...LIGHT, surface: '26 23 20', brand: '168 37 64', ink: '255 255 255' };

const CSS = `
:root {
  --font-base: "Times New Roman", Times, serif;
  --font-mono: ui-monospace, Menlo, monospace;
  --font-serif-body: Georgia, serif;
  --font-serif-display: "Playfair Display", Georgia, serif;
  --editor-paper: #ffffff;
}
:root {
  /* SEMANTIC THEME — light */
${roles(LIGHT)}
}
.dark {
${roles(DARK)}
}
.workspace { --ink-brand: 26 23 20; --surface: 255 255 255; }
@media print { :root { --surface: 255 255 255; } }
`;
const TW = `
export default { theme: { extend: {
  borderRadius: { lg: '0.75rem', xl: '1rem', '2xl': '1.25rem' },
  boxShadow: { 'soft': '0 2px 15px -3px rgba(0, 0, 0, 0.1), 0 4px 6px -2px rgba(0, 0, 0, 0.05)', 'warm': '0 4px 25px -5px rgba(0,0,0,.15)' },
}}}`;

test('triplets become hex, anything else is refused', () => {
  assert.equal(tripletToHex('139 26 43', '--brand'), '#8b1a2b');
  assert.equal(tripletToHex(' 255 255 255 ', '--ink'), '#ffffff');
  assert.throws(() => tripletToHex('#8b1a2b', '--brand'), /expected an rgb triplet/);
  assert.throws(() => tripletToHex('rgb(var(--brand))', '--x'), /expected an rgb triplet/);
});

test('blocks are keyed by selector and the first declaration of a name wins', () => {
  const sels = blocks(CSS).map(([s]) => s);
  assert.deepEqual(sels, [':root', ':root', '.dark', '.workspace', ':root']);
  const root = declarations(CSS, ':root');
  assert.equal(root.get('--surface'), '250 247 244', 'the print override block comes later and loses');
  assert.equal(root.get('--font-base'), '"Times New Roman", Times, serif');
  assert.equal(declarations(CSS, '.dark').get('--brand'), '168 37 64');
  assert.equal(declarations(CSS, '.workspace').get('--ink-brand'), '26 23 20', 'other selectors are kept apart');
});

test('tailwind tables parse quoted and bare keys', () => {
  assert.deepEqual(tailwindTable(TW, 'borderRadius'), [['lg', '0.75rem'], ['xl', '1rem'], ['2xl', '1.25rem']]);
  assert.equal(tailwindTable(TW, 'boxShadow')[0][1], '0 2px 15px -3px rgba(0, 0, 0, 0.1), 0 4px 6px -2px rgba(0, 0, 0, 0.05)');
  assert.throws(() => tailwindTable(TW, 'spacing'), /no spacing table/);
});

test('buildTokens carries every colour role for both themes, fonts, radii and shadows', () => {
  const t = buildTokens({ css: CSS, tailwind: TW });
  assert.equal(t.light.length, COLOR_ROLES.length + 4 + 3 + 2);
  assert.equal(t.dark.length, COLOR_ROLES.length);
  const light = Object.fromEntries(t.light.map(([k, v]) => [k, v]));
  assert.equal(light['--color-brand'], '#8b1a2b');
  assert.equal(light['--color-cardinal-bright'], '#f43f5e');
  assert.equal(light['--radius-lg'], '0.75rem');
  assert.equal(light['--shadow-warm'], '0 4px 25px -5px rgba(0,0,0,.15)');
  assert.ok(!('--editor-paper' in light), 'component vars are not tokens');
  const dark = Object.fromEntries(t.dark.map(([k, v]) => [k, v]));
  assert.equal(dark['--color-brand'], '#a82540');
  assert.equal(dark['--color-ink'], '#ffffff');
  assert.equal(dark['--color-line'], '#d8d3cc', 'a role the dark block declares identically still carries');
});

test('a missing role is a hard stop, never a default', () => {
  assert.throws(() => buildTokens({ css: CSS.replace('--cream: 249 228 193;', ''), tailwind: TW }), /:root: --cream is not declared/);
});

test('the sheet is Claude Design shaped: annotated declarations, a dark theme selector, link colours', () => {
  const sheet = renderSheet(buildTokens({ css: CSS, tailwind: TW }), 'brand/index.css + brand/tailwind.config.ts');
  assert.match(sheet, /^\/\* GENERATED by the design skill \(ds-tokens\.mjs\) from brand\/index\.css \+ brand\/tailwind\.config\.ts\./);
  assert.ok(sheet.includes('\n:root{\n--color-surface:#faf7f4; /* @kind color */\n'));
  assert.ok(sheet.includes('--font-base:"Times New Roman", Times, serif; /* @kind font */'));
  assert.ok(sheet.includes('\n[data-theme="dark"]{\n--color-surface:#1a1714; /* @kind color */\n'));
  assert.ok(sheet.endsWith('a{color:var(--color-ink-brand)}a:hover{color:var(--color-cardinal-bright)}\n'));
});
